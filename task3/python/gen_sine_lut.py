#!/usr/bin/env python3
"""
Task 3 (v2) - VHDL package generator for the FPGA built-in test-tone DDS.

Generates  ../fpga/rtl/sine_lut_pkg.vhd  containing
  * SINE_LUT       : 1024 x 12-bit unsigned sine table (offset binary, mid = 2048)
  * TONE_PHASE_INC : 8 phase increments (32-bit DDS) selected by SW[3:1]
  * TONE_FREQ_HZ   : the matching frequencies (for documentation / simulation)

The DDS lets you verify the whole FPGA -> ESP32 -> PC chain (and the FFT
frequency axis) without any analog hardware connected.

Usage:
    python gen_sine_lut.py              # default amplitude 1800 codes
    python gen_sine_lut.py --amp 1500
"""
import argparse
import math
from pathlib import Path

FS_HZ = 16_000          # must match FS_HZ generic of task3_top
LUT_BITS = 10           # 1024 entries
ACC_BITS = 32           # phase accumulator width
ADC_BITS = 12
MID = 1 << (ADC_BITS - 1)

# SW[3:1] -> tone.  N = 1024, delta_f = 15.625 Hz
#  000 1000.0  Hz : exactly bin 64           (no leakage with rectangular window)
#  001 1007.8125 Hz: bin 64.5                (worst-case leakage -> compare Hann)
#  010  440.0  Hz : A4, non-integer bin
#  011  250.0  Hz : bin 16
#  100 2000.0  Hz
#  101 3000.0  Hz
#  110 5000.0  Hz
#  111 7000.0  Hz : close to Nyquist (8 kHz)
TONES_HZ = [1000.0, 1007.8125, 440.0, 250.0, 2000.0, 3000.0, 5000.0, 7000.0]


def build(amp: int) -> str:
    n = 1 << LUT_BITS
    lut = [int(round(MID + amp * math.sin(2 * math.pi * i / n))) for i in range(n)]
    lut = [min(max(v, 0), (1 << ADC_BITS) - 1) for v in lut]
    incs = [int(round(f / FS_HZ * (1 << ACC_BITS))) for f in TONES_HZ]
    assert all(0 < x < 2**31 for x in incs), "phase increment must fit a VHDL natural"

    lines = []
    w = lines.append
    w("-- =========================================================================")
    w("-- AUTO-GENERATED by task3_v2/python/gen_sine_lut.py  --  DO NOT EDIT")
    w(f"-- Sine LUT: {n} x {ADC_BITS}-bit, mid = {MID}, amplitude = {amp} codes")
    w(f"-- DDS: {ACC_BITS}-bit phase accumulator clocked at Fs = {FS_HZ} Hz")
    w("-- =========================================================================")
    w("library ieee;")
    w("use ieee.std_logic_1164.all;")
    w("use ieee.numeric_std.all;")
    w("")
    w("package sine_lut_pkg is")
    w(f"  constant LUT_ADDR_BITS : natural := {LUT_BITS};")
    w(f"  constant DDS_ACC_BITS  : natural := {ACC_BITS};")
    w(f"  type sine_lut_t is array (0 to {n - 1}) of natural range 0 to {(1 << ADC_BITS) - 1};")
    w("  type phase_inc_t is array (0 to 7) of natural;")
    w("")
    w("  -- Phase increment = round(f / Fs * 2^32)")
    w("  constant TONE_PHASE_INC : phase_inc_t := (")
    for i, (f, inc) in enumerate(zip(TONES_HZ, incs)):
        sep = "," if i < len(incs) - 1 else " "
        w(f"    {inc:>10d}{sep}  -- SW[3:1]={i:03b} : {f:.4f} Hz")
    w("  );")
    w("")
    w("  constant SINE_LUT : sine_lut_t := (")
    per_line = 12
    for i in range(0, n, per_line):
        chunk = lut[i:i + per_line]
        txt = ", ".join(f"{v:4d}" for v in chunk)
        end = "," if i + per_line < n else ""
        w(f"    {txt}{end}")
    w("  );")
    w("end package sine_lut_pkg;")
    w("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--amp", type=int, default=1800, help="sine amplitude in ADC codes (<=2047)")
    ap.add_argument("--out", type=Path,
                    default=Path(__file__).resolve().parent.parent / "fpga" / "rtl" / "sine_lut_pkg.vhd")
    args = ap.parse_args()
    if not 0 < args.amp < MID:
        ap.error("amplitude must be 1..2047")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(args.amp))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
